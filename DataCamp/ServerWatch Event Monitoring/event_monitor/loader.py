def load_json_alerts(file_path):
    """Load a JSON-lines alerts file and return a list of dicts.

    Each non-blank line of the file contains a single JSON object.
    Blank lines should be skipped.

    Parameters
    ----------
    file_path : str or Path
        Path to the .jsonl alerts file.

    Returns
    -------
    list[dict]
        List of alert records.

    Raises
    ------
    FileNotFoundError
        If the file does not exist.
    ValueError
        If a non-blank line contains invalid JSON.
    """
    path = Path(file_path)
    if not path.is_file():
        raise FileNotFoundError(f"Alerts file not found: {file_path}")
    
    alerts = []
    with open(path, "r") as f:
        for num, line in enumerate(f, start=1):
            clean_line = line.strip()
            if not clean_line:
                continue
            try:
                alerts.append(json.loads(clean_line))
            except json.JSONDecodeError as e:
                raise ValueError(f"Invalid JSON on line {num}: {e}")
                
    return alerts
